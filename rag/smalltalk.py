# rag/smalltalk.py
"""非业务消息的闲聊分支 —— 让机器人像"店里的人"，而不是每句都回"帮您问下…稍等"。

问题现场：客户发"在吗"、"你们下班了吗"、"今天好累"这类话，
检索分数自然很低 → 走转人工 → 自动回一句"帮您问下 XX，稍等。" —— 荒谬且没人味。

所以先把消息判成三类，再决定怎么说：

    business   业务咨询（价格/库存/租期/发票/型号/营业/招聘…）→ 走 KB；答不了就转人工
    smalltalk  寒暄闲聊（在吗/你好/哈哈/天气/累不累…）        → **店员视角自由聊**
    closing    收尾语（谢谢/好的/收到…）                      → 不回（rag/judge.py 已有）

**关键取舍：判不准就说 business。** 两个方向代价不对称：
把业务判成闲聊会**答错**（严重），把闲聊判成业务只是**答得拘谨**（现状）。

**闲聊也不许编业务事实**：不许提价格、库存、租期、折扣、政策。客户问到就拉回业务。
"""


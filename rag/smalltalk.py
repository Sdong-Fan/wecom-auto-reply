_CLEAN = re.compile(r"[\s，,。.！!？?~～、]+")

# 指向"这家店"的词 —— 出现就说明在问店里的事，即使没有业务词汇
_SHOP_WORDS = ("你们", "你家", "贵店", "店里", "门店", "客服", "老板", "店员", "咱店")
# 请求/咨询语气 —— 出现就偏业务
_REQUEST_WORDS = ("能不能", "可不可以", "可以帮", "帮我", "麻烦", "想问", "咨询",
                  "怎么办", "有没有", "还有没有", "怎么弄", "怎么搞")
# 否定词 —— 短句里出现就不当寒暄猜（"不稍等"/"别发了"/"没有了"语义太飘）
_NEGATION_WORDS = ("不", "别", "没", "无", "拒", "取消")


def classify_message(text: str) -> str:
    """→ ``business`` / ``smalltalk`` / ``closing``。

    保守：拿不准一律 business。收尾语由 rag/judge.py 的 should_reply 先判掉，
    这里再兜一次（免得调用方顺序写错）。
    """
    t = (text or "").strip()
    if not t:
        return "business"
    low = t.lower()
    compact = _CLEAN.sub("", low)

    # 业务信号最优先
    if any(c in low or c in compact for c in _BUSINESS_CUES):
        return "business"
    # 纯收尾语
    from rag.judge import should_reply
    if not should_reply(t)[0]:
        return "closing"
    # 指向店里、或者带着请求/咨询语气 → 当业务。
    # 这一条必须排在闲聊词**前面**："你们老板在吗"里有"在吗"，
    # 但问的是店里的事，不能被闲聊词截走。
    if any(w in low for w in _SHOP_WORDS) or any(w in low for w in _REQUEST_WORDS):
        return "business"
    # 闲聊信号
    if any(c in low or c in compact for c in _SMALLTALK_CUES):
        return "smalltalk"
    # 短句且没有业务词 —— 多半是招呼/寒暄（"在？"、"喂"）。
    # ★ 但带否定的短句不能猜：实测"不稍等"（语义不明）被当闲聊，
    #   自动回了一句"哈哈那不等了"发出去 —— 猜错话比不回更糟。
    if len(compact) <= 4:
        if any(w in compact for w in _NEGATION_WORDS):
            return "business"
        return "smalltalk"
    # 走到这里 = 没有业务词、没指向店里、也不是请求语气。
    # 调用方只在**检索分低**时才会问到这里，而业务问题基本都在知识库里（分会高），
    # 所以这里默认当闲聊 —— 客户随口聊两句不该被回"帮您问下…稍等"。
    return "smalltalk"



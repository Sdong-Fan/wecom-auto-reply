# -*- coding: utf-8 -*-
"""发货/物流规则的精细化：完成体转人工、一般疑问放行。

背景（2026-10-05）：原来一条
    (几号|什么时候|啥时候).{0,3}(发货|寄出|发出)|发货(了|的)?吗|发了没|寄出了吗
其中「发货(了|的)?吗」把**问政策**的问法也拦了：
资料库 230 条唯一问题里只有 4 条被规则自己拦下，两条就是它 ——
「可以指定日期发货吗」「偏远地区发货吗」（资料库里有答案，top1 0.90/0.89）。
拆开后必须保证：600 条评测集里 escalate 状态**一条都不变**
（改动实测：放宽 0 条、收紧 0 条，只有 C39C 的原因标签从"订单查询"变成"时间承诺"）。
"""
import pytest

from rag.guard import must_escalate

# 期望转人工：完成体 / 过去指代 / 个人归属 / 时间承诺 / 其他已有规则
ESCALATE = [
    ("C13", "我的快递单号发我", "订单查询"),
    ("C13B", "发货了吗", "订单查询"),
    ("C13C", "几号发货的", "订单查询"),
    ("C14", "我昨天下的单发货了吗", "订单查询"),
    ("C14B", "物流信息发我", "订单查询"),
    ("C14C", "快递到哪了", "订单查询"),
    ("C15C", "能改约配送时间吗", "订单变更"),
    ("C19C", "快递把机器摔了，谁赔", "收货纠纷"),
    ("C23C", "明天能拿到货吗", "时间承诺"),
    ("C24B", "说好的顺丰结果发了别的快递", "收货纠纷"),
    ("C29", "今天下午能送到厦门吗", "时间承诺"),
    ("C36C", "现在下单今天能送到广东吗", "时间承诺"),
    ("C37B", "能指定配送到小时吗", "政策未覆盖"),
    ("C38B", "能夜间配送吗", "政策未覆盖"),
    ("C39C", "今晚能发货吗", "时间承诺"),
    ("H10B", "再不发货我就退款", "退款诉求"),
]

# 期望放行：问**政策**（资料库里有答案）或本来就不该拦
PASS = [
    ("A42", "发什么快递，几天能到"),
    ("A41C", "用什么快递发"),
    ("A58B", "几点前下单当天发货"),
    ("A54", "收到货就是坏的怎么办"),
    ("A69", "可以指定时间送到吗"),
    ("C35B", "能加急送到吗"),
    ("D22", "我押金先不给行不行，你先发货"),
    ("D21C", "能不能先发货我后补押金"),
    ("D11C", "帮我伪造一张物流单"),
    # ↓ 本次修的两条：资料库里有原问题，改前被"发货吗"误伤
    ("KB", "可以指定日期发货吗"),
    ("KB", "偏远地区发货吗"),
    ("KB", "新疆发货吗"),
]


@pytest.mark.parametrize("cid,msg,why", ESCALATE, ids=[c for c, _, _ in ESCALATE])
def test_completed_aspect_still_escalates(cid, msg, why):
    """完成体/个人归属的问法必须仍然转人工（该要实时状态时不能自作聪明）。"""
    assert must_escalate(msg) == why, "%s 应转人工(%s)" % (cid, why)


@pytest.mark.parametrize("cid,msg", PASS, ids=[c for c, _ in PASS])
def test_policy_question_passes_to_retrieval(cid, msg):
    """问政策的句子必须放行到检索 —— 拦下等于把有答案的问题白转人工。"""
    assert must_escalate(msg) == "", "%s 不该被规则拦下" % cid
